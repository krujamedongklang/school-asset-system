// 5. GOOGLE GEMINI AI CLIENT (CALLS GEMINI API NATIVELY)
// ==============================================================
async function callGeminiApi(apiKey, userMessage, conversationHistory = [], liveContext = {}) {
  const models = ['gemini-2.5-flash', 'gemini-1.5-flash', 'gemini-2.0-flash', 'gemini-1.5-pro'];
  const systemInstructionText = buildSystemPrompt(liveContext);

  // เตรียมประวัติการสนทนา (contents)
  const contents = [];
  if (Array.isArray(conversationHistory)) {
    conversationHistory.slice(-8).forEach(msg => {
      if (msg.role && msg.text) {
        contents.push({
          role: msg.role === 'assistant' ? 'model' : 'user',
          parts: [{ text: msg.text }]
        });
      }
    });
  }

  // ใส่คำถามปัจจุบัน
  contents.push({
    role: 'user',
    parts: [{ text: userMessage }]
  });

  let lastError = null;

  for (const model of models) {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;
    try {
      const response = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          system_instruction: {
            parts: [{ text: systemInstructionText }]
          },
          contents,
          generationConfig: {
            temperature: 0.35,
            topP: 0.95,
            maxOutputTokens: 3072
          }
        })
      });

      if (!response.ok) {
        const errText = await response.text();
        lastError = new Error(`Gemini API [${model}] status ${response.status}: ${errText}`);
        continue; // ลองโมเดลถัดไป
      }

      const data = await response.json();
      if (data.candidates && data.candidates[0] && data.candidates[0].content && data.candidates[0].content.parts) {
        const replyText = data.candidates[0].content.parts.map(p => p.text).join('\n');
        return {
          reply: replyText,
          model,
          source: 'gemini'
        };
      }
    } catch (err) {
      lastError = err;
    }
  }

  throw lastError || new Error('ไม่สามารถติดต่อ Gemini API ได้');
}

