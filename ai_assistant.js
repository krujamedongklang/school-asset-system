// 6. MAIN CHAT HANDLER
// ==============================================================
async function handleChat(userMessage, conversationHistory = [], liveContext = {}) {
  const apiKey = getGeminiApiKey();

  // หากมี Gemini API Key ให้ใช้ Gemini AI
  if (apiKey) {
    try {
      const geminiResult = await callGeminiApi(apiKey, userMessage, conversationHistory, liveContext);
      return geminiResult;
    } catch (err) {
      console.warn('⚠️ Gemini API error, falling back to built-in expert engine:', err.message);
      const fallbackReply = queryBuiltInExpert(userMessage, liveContext);
      return {
        reply: fallbackReply + `\n\n*(หมายเหตุ: ระบบสลับมาใช้คลังความรู้ภายใน สพฐ. ชั่วคราว เนื่องจาก Gemini API แจ้งเตือน: ${err.message})*`,
        source: 'builtin_fallback'
      };
    }
  }

  // หากยังไม่ได้ใส่ API Key ให้ใช้ Built-in Expert Engine โดยตรง
  const expertReply = queryBuiltInExpert(userMessage, liveContext);
  return {
    reply: expertReply,
    source: 'builtin_expert'
  };
}

