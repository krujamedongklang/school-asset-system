const fs = require('fs');
const path = require('path');

const CONFIG_FILE = path.join(__dirname, 'ai_config.json');

// โหลด API Key จาก Environment หรือ ai_config.json
function getGeminiApiKey() {
  let key = process.env.GEMINI_API_KEY || '';
  if (!key && fs.existsSync(CONFIG_FILE)) {
    try {
      const cfg = JSON.parse(fs.readFileSync(CONFIG_FILE, 'utf8'));
      key = cfg.gemini_api_key || '';
    } catch (e) {}
  }
  return key.trim();
}

function setGeminiApiKey(key) {
  const cfg = { gemini_api_key: (key || '').trim(), updated_at: new Date().toISOString() };
  fs.writeFileSync(CONFIG_FILE, JSON.stringify(cfg, null, 2), 'utf8');
  return { success: true, message: 'บันทึก Gemini API Key เรียบร้อยแล้ว' };
}

